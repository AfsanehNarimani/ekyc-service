import numpy as np

from ai_modules.face_verification.domain.base_face_embedding_similarity_calculator import (
    BaseFaceEmbeddingSimilarityCalculator,
)
from ai_modules.face_verification.domain.face_embedding import (
    FaceEmbedding,
)


class CosineFaceEmbeddingSimilarityCalculator(
    BaseFaceEmbeddingSimilarityCalculator,
):
    def calculate_similarity(
        self,
        reference_embedding: FaceEmbedding,
        candidate_embedding: FaceEmbedding,
    ) -> float:
        if reference_embedding.model_name != candidate_embedding.model_name:
            raise ValueError(
                "Face embeddings must be generated by the same model.",
            )

        if reference_embedding.vector.shape != candidate_embedding.vector.shape:
            raise ValueError(
                "Face embedding vectors must have the same dimensions.",
            )

        reference_vector = reference_embedding.vector
        candidate_vector = candidate_embedding.vector

        reference_vector_norm = np.linalg.norm(
            reference_vector,
        )
        candidate_vector_norm = np.linalg.norm(
            candidate_vector,
        )

        if reference_vector_norm == 0 or candidate_vector_norm == 0:
            return 0.0

        return float(
            np.dot(
                reference_vector,
                candidate_vector,
            )
            / (reference_vector_norm * candidate_vector_norm),
        )
